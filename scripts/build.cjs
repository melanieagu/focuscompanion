const fs = require('node:fs');
const path = require('node:path');
const solc = require('solc');
const root = path.join(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'contracts/FocusPact.sol'), 'utf8');
const input = { language: 'Solidity', sources: { 'FocusPact.sol': { content: source } }, settings: { optimizer: { enabled: true, runs: 200 }, evmVersion: 'paris', outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object', 'evm.deployedBytecode.object'] } } } };
const output = JSON.parse(solc.compile(JSON.stringify(input)));
for (const error of output.errors || []) console.log(error.formattedMessage);
if ((output.errors || []).some(error => error.severity === 'error')) process.exit(1);
const result = output.contracts['FocusPact.sol'].FocusPact;
const artifact = { compiler: solc.version(), abi: result.abi, bytecode: '0x' + result.evm.bytecode.object, deployedBytecode: '0x' + result.evm.deployedBytecode.object };
fs.writeFileSync(path.join(root, 'contract-artifact.js'), 'window.FOCUS_ARTIFACT = ' + JSON.stringify(artifact, null, 2) + ';\n');
fs.mkdirSync(path.join(root, 'build'), { recursive: true });
fs.writeFileSync(path.join(root, 'build/FocusPact.json'), JSON.stringify(artifact, null, 2));
const ethersEntry = require.resolve('ethers');
const ethersRoot = path.resolve(path.dirname(ethersEntry), '..');
fs.mkdirSync(path.join(root, 'vendor'), { recursive: true });
fs.copyFileSync(path.join(ethersRoot, 'dist/ethers.umd.min.js'), path.join(root, 'vendor/ethers.umd.min.js'));
fs.copyFileSync(path.join(ethersRoot, 'LICENSE.md'), path.join(root, 'vendor/ETHERS-LICENSE.md'));
console.log('Built contract artifact and local ethers library. Now run npm test, then npm start.');
